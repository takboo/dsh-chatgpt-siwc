import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ args: ['--no-sandbox'] })
try {
  const desktop = await browser.newPage({ viewport: { width: 720, height: 420 } })
  const errors = []
  desktop.on('pageerror', error => errors.push(error.message))
  await desktop.goto('file:///fixture/index.html')
  await desktop.getByRole('button', { name: 'Continue with ChatGPT' }).click()
  await desktop.getByRole('button', { name: 'Got it' }).click()
  await desktop.getByText('Jules Fixture', { exact: true }).waitFor()
  const id = desktop.getByText('c149080e-6cf5-4ccc-a571-65fa173d35f5', { exact: true })
  assert.equal(await id.isVisible(), false)
  const accountMenu = desktop.getByRole('button', { name: 'Account actions · Jules Fixture' })
  await accountMenu.click()
  await id.waitFor()
  await desktop.keyboard.press('Escape')
  await id.waitFor({ state: 'hidden' })
  assert.equal(await desktop.getByRole('button', { name: 'Refresh models' }).count(), 0)
  assert.equal(await desktop.getByRole('heading', { name: 'Plan usage' }).count(), 0)
  assert.equal(await desktop.getByRole('link', { name: /Manage usage/ }).count(), 0)
  assert.equal(await desktop.getByRole('switch', { name: 'ChatGPT web search' }).getAttribute('aria-checked'), 'false')
  const help = desktop.getByRole('button', { name: 'About ChatGPT web search' })
  const tooltip = desktop.getByRole('tooltip').filter({ hasText: 'You can choose your chat model separately.' })
  await help.hover()
  await tooltip.waitFor()
  await help.click()
  await desktop.mouse.move(2, 2)
  await tooltip.waitFor()
  await desktop.keyboard.press('Escape')
  await tooltip.waitFor({ state: 'hidden' })
  await desktop.screenshot({ path: '/fixture/wide.png', fullPage: true })
  await accountMenu.click()
  await desktop.getByRole('menuitem', { name: 'Sign out' }).click()
  await desktop.getByText('Remote revocation could not be confirmed.', { exact: false }).waitFor()
  assert.deepEqual(errors, [])

  const narrow = await browser.newPage({ viewport: { width: 320, height: 460 } })
  await narrow.goto('file:///fixture/index.html?dark=1&lang=zh&quota=1')
  await narrow.getByRole('button', { name: '使用 ChatGPT 继续' }).click()
  await narrow.getByRole('button', { name: '知道了' }).click()
  await narrow.getByRole('alert').getByText('已达到 ChatGPT 用量限制。').waitFor()
  assert.equal(await narrow.getByRole('link', { name: '管理用量' }).getAttribute('href'), 'https://chatgpt.com/settings/usage')
  assert.equal(await narrow.evaluate(() => document.documentElement.scrollWidth), 320)
  await narrow.screenshot({ path: '/fixture/narrow.png', fullPage: true })

  await desktop.goto('file:///fixture/index.html?offline=1')
  await desktop.getByText('This offline build cannot connect to a real account.').waitFor()
  assert.equal(await desktop.getByRole('button', { name: 'Continue with ChatGPT' }).count(), 0)
  console.log('Fixed Chromium: compact settings, account disclosure, usage link, quota, logout and offline view verified')
} finally {
  await browser.close()
}
